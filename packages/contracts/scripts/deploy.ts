import { network } from 'hardhat';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { keccak256 } from 'viem';
const connection = await network.create();
const client = await connection.viem.getPublicClient();
const wallets = await connection.viem.getWalletClients();
if (!wallets.length) throw new Error('Set DEPLOYER_PRIVATE_KEY in root .env (test-only wallet).');
const [wallet] = wallets;
const balance = await client.getBalance({ address: wallet.account.address });
if (balance === 0n) throw new Error(`Fund deployer ${wallet.account.address} with test MON before deploying.`);
const artifact = JSON.parse(await readFile(new URL('../artifacts/contracts/OrvenaRegistry.sol/OrvenaRegistry.json', import.meta.url), 'utf8'));
const transactionHash = await wallet.deployContract({ abi: artifact.abi, bytecode: artifact.bytecode });
const receipt = await client.waitForTransactionReceipt({ hash: transactionHash });
if (receipt.status !== 'success' || !receipt.contractAddress) throw new Error('Registry deployment reverted.');
const registry = { address: receipt.contractAddress };
const chainId = await client.getChainId();
const directory = new URL('../../../deployments/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL(`${chainId}.json`, directory), JSON.stringify({ chainId, registry: registry.address, deployer: wallet.account.address, deployedAt: new Date().toISOString(), transactionHash, creationBytecodeHash: keccak256(artifact.bytecode), block: receipt.blockNumber.toString(), gasUsed: receipt.gasUsed.toString(), effectiveGasPrice: receipt.effectiveGasPrice.toString() }, null, 2));
console.log(JSON.stringify({ chainId, registry: registry.address }, null, 2));
console.log('Copy registry address to VITE_REGISTRY_ADDRESS and REGISTRY_ADDRESS in root .env.');
