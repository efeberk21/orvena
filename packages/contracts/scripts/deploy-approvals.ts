import { network } from 'hardhat';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { isAddress, keccak256 } from 'viem';
const connection = await network.create();
const client = await connection.viem.getPublicClient();
const chainId = await client.getChainId();
if (![10143, 31337].includes(chainId)) throw new Error('Only local EVM and Monad testnet are supported.');
const deployment = JSON.parse(await readFile(new URL(`../../../deployments/${chainId}.json`, import.meta.url), 'utf8'));
const registry = chainId === 10143 ? process.env.REGISTRY_ADDRESS || deployment.registry : deployment.registry;
if (!isAddress(registry) || !await client.getCode({ address: registry })) throw new Error('Deploy/configure the identity registry first.');
const [wallet] = await connection.viem.getWalletClients();
if (!wallet || await client.getBalance({ address: wallet.account.address }) === 0n) throw new Error('Fund the configured test-only deployer.');
const artifact = JSON.parse(await readFile(new URL('../artifacts/contracts/OrvenaApprovals.sol/OrvenaApprovals.json', import.meta.url), 'utf8'));
const hash = await wallet.deployContract({ abi: artifact.abi, bytecode: artifact.bytecode, args: [registry] });
const receipt = await client.waitForTransactionReceipt({ hash });
if (receipt.status !== 'success' || !receipt.contractAddress) throw new Error('Approval contract deployment reverted.');
await mkdir(new URL('../../../deployments/', import.meta.url), { recursive: true });
const metadata = { chainId, registry, approvals: receipt.contractAddress, transactionHash: hash, block: receipt.blockNumber.toString(), deployedAt: new Date().toISOString(), creationBytecodeHash: keccak256(artifact.bytecode), gasUsed: receipt.gasUsed.toString(), effectiveGasPrice: receipt.effectiveGasPrice.toString() };
await writeFile(new URL(`../../../deployments/approvals-${chainId}.json`, import.meta.url), JSON.stringify(metadata, null, 2));
console.log(JSON.stringify(metadata, null, 2));
